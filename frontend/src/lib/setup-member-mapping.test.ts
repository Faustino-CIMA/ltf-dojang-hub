import { SETUP_MEMBER_TARGET_FIELDS, shareMemberIdColumn } from "@/lib/setup-member-mapping";

describe("setup member id mapping", () => {
  it("does not offer the autogenerated member id as a target", () => {
    const keys = SETUP_MEMBER_TARGET_FIELDS.map((field) => field.key);
    expect(keys).toEqual([
      "wt_licenseid",
      "ltf_licenseid",
      "first_name",
      "last_name",
      "club_name",
      "sex",
      "date_of_birth",
      "primary_license_role",
      "secondary_license_role",
      "membership_end_date",
    ]);
  });

  it("fills both license ids from the Member ID column", () => {
    const mapping = shareMemberIdColumn({
      ltf_licenseid: "Member ID",
      first_name: "Preferred First Name",
    });
    expect(mapping.wt_licenseid).toBe("Member ID");
    expect(mapping.ltf_licenseid).toBe("Member ID");
  });

  it("drops a generated member id even when the same column fills both licenses", () => {
    const mapping = shareMemberIdColumn({
      member_id: "Member ID",
      id: "Member ID",
      ltf_licenseid: "Member ID",
    });
    expect(mapping.wt_licenseid).toBe("Member ID");
    expect(mapping.ltf_licenseid).toBe("Member ID");
    expect(mapping).not.toHaveProperty("member_id");
    expect(mapping).not.toHaveProperty("id");
  });

  it("keeps a dedicated WT column and does not reuse a different LTF column", () => {
    expect(shareMemberIdColumn({ wt_licenseid: "WT License", ltf_licenseid: "Member ID" }).wt_licenseid).toBe("WT License");
    expect(shareMemberIdColumn({ ltf_licenseid: "LTF License" }).wt_licenseid).toBeUndefined();
  });
});
